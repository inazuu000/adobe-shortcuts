interface Opts {
  aliases?: string[];
  winAlt?: string[];
  status?: 'verified' | 'unverified';
  note?: string;
}

function t(
  id: string, name: string, category: string, key: string | null, level: Level,
  description: string, fn: string, example: string, tip: string, o: Opts = {},
): Tool {
  return {
    id, software: 'illustrator', category, name,
    aliases: o.aliases ?? [], win: key, mac: key, winAlt: o.winAlt, macAlt: o.winAlt,
    description, fn, example, tip,
    icon: `icons/ai/${id}.png`, level,
    status: o.status ?? 'verified', version: VERSION, note: o.note,
  };
}

