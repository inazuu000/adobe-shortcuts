import type { Command, Level } from './types';

const VERSION = 'Illustrator 2024–2026 (desktop)';

interface Opts {
  aliases?: string[];
  winAlt?: string[];
  macAlt?: string[];
  note?: string;
}

function c(
  id: string, name: string, category: string, win: string, mac: string, level: Level,
  description: string, whenToUse: string, example: string, o: Opts = {},
): Command {
  return {
    id: `ai-${id}`, software: 'illustrator', category, name,
    aliases: o.aliases ?? [], win, mac, winAlt: o.winAlt, macAlt: o.macAlt,
    description, whenToUse, example, level, status: 'verified', version: VERSION, note: o.note,
  };
}

