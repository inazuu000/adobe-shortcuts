const OTHER = 'Other Toolbar Buttons';

interface Opts {
  aliases?: string[];
  winAlt?: string[];
  status?: 'verified' | 'unverified';
  version?: string;
  note?: string;
}

// id, name, category, key, level, description, function (exam text, never names the tool), example, tip
function t(
  id: string, name: string, category: string, key: string | null, level: Level,
  description: string, fn: string, example: string, tip: string, o: Opts = {},
): Tool {
  return {
    id, software: 'photoshop', category, name,
    aliases: o.aliases ?? [], win: key, mac: key, winAlt: o.winAlt, macAlt: o.winAlt,
    description, fn, example, tip,
    icon: `icons/ps/${id}.png`, level,
    status: o.status ?? 'verified', version: o.version ?? VERSION, note: o.note,
  };
}

